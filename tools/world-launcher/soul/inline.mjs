#!/usr/bin/env node
// Worlds serve eden.mjs as one file and many tools copy it alone, so the CLI's modules are inlined into a generated
// block of it. Edit the module, then run this. `--check` changes nothing and fails on a stale block (the test does that).
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = (name) => fileURLToPath(new URL(name, import.meta.url));
const mark = (file) => file.split("/").pop();
/** module file -> the name eden.mjs knows it by. A module comes after anything it imports. */
export const MODULES = [["home.mjs", "soulHome"], ["../../edge-skill/memory-folder.mjs", "soulRecords"], ["brief.mjs", "soulBrief"], ["people.mjs", "soulPeople"], ["consolidate.mjs", "soulConsolidate"], ["memory.mjs", "soulMemory"]];

/** A module as a generated block: node imports hoisted under private names, another inlined module read from its closure,
 *  its exports returned from one closure. */
export function inlineBlock(source, file, name) {
  const heads = [], unpacks = [];
  const body = source.replace(/^import\s*\{([^}]*)\}\s*from\s*["'](node:[a-z_/]+|\.[^"']+)["'];\n/gm, (_, names, from) => {
    const list = names.trim().replace(/\s+as\s+/g, ": ");
    if (from.startsWith(".")) {
      const known = MODULES.find(([f]) => f === from.replace(/^\.\//, ""))?.[1];
      if (!known) throw new Error(`${file}: ${from} is not an inlined module`);
      unpacks.push(`const { ${list} } = ${known};`);
      return "";
    }
    const alias = `${name}$${from.slice(5).replace(/\W/g, "_")}`;
    heads.push(`import * as ${alias} from "${from}";`);
    unpacks.push(`const { ${list} } = ${alias};`);
    return "";
  });
  if (/^import\b/m.test(body)) throw new Error(`${file}: only node: imports and inlined modules can be inlined`);
  const exported = [...body.matchAll(/^export (?:async )?(?:function|const) (\w+)/gm)].map((m) => m[1]);
  for (const m of body.matchAll(/^export const (.+)$/gm)) for (const more of m[1].matchAll(/,\s*(\w+) = /g)) if (!/["(]/.test(m[1].slice(0, more.index).split("=").at(-1).replace(/"[^"]*"/g, ""))) exported.push(more[1]);
  return [`// <inline ${mark(file)}> generated by inline.mjs: edit ${mark(file)}, not this block`, ...heads, `const ${name} = (() => {`, ...unpacks,
    body.replace(/^export /gm, "").trim(), `return { ${[...new Set(exported)].join(", ")} };`, "})();", `// </inline ${mark(file)}>`].join("\n");
}

export function withBlocks(cli, read = (f) => readFileSync(here(f), "utf8")) {
  let out = cli;
  for (const [file, name] of MODULES) {
    const block = inlineBlock(read(file), file, name);
    const start = out.indexOf(`// <inline ${mark(file)}>`), endTag = `// </inline ${mark(file)}>`, end = out.indexOf(endTag);
    if (start < 0 || end < 0) throw new Error(`eden.mjs has no block for ${file}`);
    out = out.slice(0, start) + block + out.slice(end + endTag.length);
  }
  return out;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const file = here("eden.mjs"), cli = readFileSync(file, "utf8"), next = withBlocks(cli);
  if (process.argv.includes("--check")) { if (next !== cli) { console.error("eden.mjs is stale: run node tools/world-launcher/soul/inline.mjs"); process.exit(1); } }
  else writeFileSync(file, next);
}
