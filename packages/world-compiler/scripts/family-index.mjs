#!/usr/bin/env node
// Deterministic static imports for Node and browser consumers; no runtime filesystem discovery.
import {existsSync, readFileSync, readdirSync, writeFileSync} from 'node:fs';
import {resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

export const CORE = fileURLToPath(new URL('../src/core-kit/', import.meta.url));
export function renderFamilyIndex(core = CORE) {
  const modules = readdirSync(resolve(core, 'families'), {withFileTypes: true})
    .filter(entry => entry.isFile() && /^[a-z][a-z0-9-]*\.family\.ts$/.test(entry.name))
    .map(entry => entry.name).sort();
  return `// Generated by packages/world-compiler/scripts/family-index.mjs --write; do not edit.
// Rebuilt and compared in the package tests. Historical order is frozen in legacy.ts.
import { FAMILY_KITS as historical } from './legacy.ts';
import type { DefInput } from '../schemas.ts';
${modules.length ? "import meshLods from '../core-mesh-lods.json' with { type: 'json' };\n" : ''}${modules.map((name, i) => `import family${i} from './families/${name}';`).join('\n')}
${modules.length ? `const additions: DefInput[] = [${modules.map((_, i) => `...family${i}`).join(', ')}].map(def => {
  const lod = def.make.kind === 'mesh' ? (meshLods as Record<string, { lod1: string }>)[def.make.asset] : undefined;
  return lod ? { ...def, make: { ...def.make, ...lod } } as DefInput : def;
});
export const FAMILY_KITS: DefInput[] = [...historical, ...additions];` : 'export const FAMILY_KITS: DefInput[] = historical;'}
`;
}
export function checkFamilyIndex(core = CORE) {
  const file = resolve(core, 'index.ts');
  return existsSync(file) && readFileSync(file, 'utf8') === renderFamilyIndex(core);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length !== 1 || !['--write', '--check'].includes(args[0])) {
    console.error('usage: node packages/world-compiler/scripts/family-index.mjs --write|--check');
    process.exitCode = 2;
  } else if (args[0] === '--write') writeFileSync(resolve(CORE, 'index.ts'), renderFamilyIndex());
  else if (!checkFamilyIndex()) { console.error('Core family index is stale; regenerate with --write.'); process.exitCode = 1; }
}
